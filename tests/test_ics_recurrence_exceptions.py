    def test_overnight_event_override(self):
        """Detached override on an overnight event crossing midnight."""
        # Master: Sunday 23:00 to Monday 01:00
        # Override for Sunday June 14 moves it to Sunday 22:00 to Monday 02:00
        ics_text = (
            "BEGIN:VCALENDAR\n"
            "VERSION:2.0\n"
            "BEGIN:VEVENT\n"
            "UID:overnight-ov@example.com\n"
            "SUMMARY:Night Shift\n"
            "DTSTART:20260607T230000\n"
            "DTEND:20260608T010000\n"
            "RRULE:FREQ=WEEKLY;COUNT=2\n"
            "END:VEVENT\n"
            "BEGIN:VEVENT\n"
            "UID:overnight-ov@example.com\n"
            "RECURRENCE-ID:20260614T230000\n"
            "DTSTART:20260614T220000\n"
            "DTEND:20260615T020000\n"
            "END:VEVENT\n"
            "END:VCALENDAR\n"
        )
        path = self.write_ics(ics_text)
        # Window targeting the overridden week (June 14)
        plan = plan_ics_import(path, empty_timetable(), datetime.date(2026, 6, 14), datetime.date(2026, 6, 14))
        self.assertTrue(plan.accepted)
        self.assertEqual(plan.occurrences_generated, 1)
        self.assertEqual(len(plan.new_classes), 1)
        _, day, slot = plan.new_classes[0]
        self.assertEqual(day, "sunday")
        self.assertEqual(slot["start"], "22:00")
        self.assertEqual(slot["end"], "02:00")
        self.assertEqual(slot["subject"], "Night Shift")

        # Overlapping overnight slots in multi-week window (23:00-01:00 vs 22:00-02:00)
        # detect a scheduling conflict on Sunday per timetable invariants
        multi_plan = plan_ics_import(path, empty_timetable(), datetime.date(2026, 6, 7), datetime.date(2026, 6, 20))
        self.assertFalse(multi_plan.accepted)
        self.assertEqual(len(multi_plan.conflicts), 1)
        self.assertEqual(multi_plan.conflicts[0].day, "sunday")

