    def test_rrule_with_multiple_exdate_values_and_properties(self):
        """RRULE with multiple EXDATE values across single and multiple property lines."""
        # Weekly Mondays in June 2026: June 1, 8, 15, 22
        # EXDATE June 8 and June 22
        ics_text = (
            "BEGIN:VCALENDAR\n"
            "VERSION:2.0\n"
            "BEGIN:VEVENT\n"
            "UID:exdate-multi@example.com\n"
            "SUMMARY:Multi EXDATE\n"
            "LOCATION:Room 101\n"
            "DTSTART:20260601T100000\n"
            "DTEND:20260601T110000\n"
            "RRULE:FREQ=WEEKLY;COUNT=4\n"
            "EXDATE:20260608T100000\n"
            "EXDATE:20260622T100000\n"
            "END:VEVENT\n"
            "END:VCALENDAR\n"
        )
        path = self.write_ics(ics_text)
        from_date = datetime.date(2026, 6, 1)
        to_date = datetime.date(2026, 6, 30)

        plan = plan_ics_import(path, empty_timetable(), from_date, to_date)
        self.assertTrue(plan.accepted)
        # June 1 and June 15 remain (June 8 and 22 excluded)
        self.assertEqual(plan.occurrences_generated, 2)
        self.assertEqual(len(plan.new_classes), 1)  # Both map to Monday 10:00-11:00
        self.assertEqual(len(plan.duplicates), 1)

