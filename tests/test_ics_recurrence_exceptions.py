"""Tests for RFC 5545 recurrence exceptions, detached VEVENT overrides,
EXDATE exclusions, RDATE additions, cancellations, and timezone behavior.
"""

from __future__ import annotations

import datetime
import tempfile
import unittest
import zoneinfo
from pathlib import Path
from typing import Dict, List

from timetable.display import WEEKDAYS
from timetable.import_ics import (
    IcsImportPlan,
    plan_ics_import,
    process_event_group,
)


def empty_timetable() -> Dict[str, List[dict]]:
    return {day: [] for day in WEEKDAYS}


class TestRecurrenceExceptionsAndOverrides(unittest.TestCase):
    """Exhaustive test suite for Issue #76: Recurrence exceptions and detached overrides."""

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.dir_path = Path(self.temp_dir.name)

    def tearDown(self):
        self.temp_dir.cleanup()

    def write_ics(self, content: str) -> Path:
        path = self.dir_path / f"test_{datetime.datetime.now().timestamp()}.ics"
        path.write_text(content, encoding="utf-8")
        return path

    # =========================================================================
    # 1. Recurrence-set construction: EXDATE & RDATE
