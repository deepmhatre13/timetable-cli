    def test_override_changing_start_and_end_times(self):
        """Override changing start and end times replaces original occurrence."""
        # Weekly Mondays 10:00-11:00 (June 1, 8, 15).
        # Override for June 8 changes time to 14:00-15:30 on the same day.
        ics_text = (
            "BEGIN:VCALENDAR\n"
            "VERSION:2.0\n"
            "BEGIN:VEVENT\n"
            "UID:override-time@example.com\n"
            "SUMMARY:Algorithms\n"
            "LOCATION:Room 101\n"
            "DTSTART:20260601T100000\n"
            "DTEND:20260601T110000\n"
            "RRULE:FREQ=WEEKLY;COUNT=3\n"
            "END:VEVENT\n"
            "BEGIN:VEVENT\n"
            "UID:override-time@example.com\n"
            "RECURRENCE-ID:20260608T100000\n"
            "DTSTART:20260608T140000\n"
            "DTEND:20260608T153000\n"
            "END:VEVENT\n"
            "END:VCALENDAR\n"
        )
        path = self.write_ics(ics_text)
        plan = plan_ics_import(path, empty_timetable(), datetime.date(2026, 6, 1), datetime.date(2026, 6, 20))
        self.assertTrue(plan.accepted)
        self.assertEqual(plan.occurrences_generated, 3)

        # Resulting classes:
        # 1) Monday 10:00-11:00 Algorithms [Room 101] (from June 1 & June 15)
        # 2) Monday 14:00-15:30 Algorithms [Room 101] (from June 8 override)
        self.assertEqual(len(plan.new_classes), 2)
        times = {(c[2]["start"], c[2]["end"]) for c in plan.new_classes}
        self.assertEqual(times, {("10:00", "11:00"), ("14:00", "15:30")})

    def test_override_changing_summary_and_location_only(self):
        """Override changing only SUMMARY and LOCATION inherits times from master."""
        ics_text = (
            "BEGIN:VCALENDAR\n"
            "VERSION:2.0\n"
            "BEGIN:VEVENT\n"
            "UID:override-meta@example.com\n"
            "SUMMARY:General Lecture\n"
            "LOCATION:Auditorium A\n"
            "DTSTART:20260601T090000\n"
            "DTEND:20260601T100000\n"
            "RRULE:FREQ=WEEKLY;COUNT=2\n"
            "END:VEVENT\n"
            "BEGIN:VEVENT\n"
            "UID:override-meta@example.com\n"
            "RECURRENCE-ID:20260608T090000\n"
            "SUMMARY:Guest Lecture by Prof. Smith\n"
            "LOCATION:Auditorium B\n"
            "END:VEVENT\n"
            "END:VCALENDAR\n"
        )
        path = self.write_ics(ics_text)
        # Window targeting the overridden week (June 8)
        plan = plan_ics_import(path, empty_timetable(), datetime.date(2026, 6, 8), datetime.date(2026, 6, 8))
        self.assertTrue(plan.accepted)
        self.assertEqual(plan.occurrences_generated, 1)
        self.assertEqual(len(plan.new_classes), 1)
        _, day, slot = plan.new_classes[0]
        self.assertEqual(day, "monday")
        self.assertEqual(slot["subject"], "Guest Lecture by Prof. Smith")
        self.assertEqual(slot["room"], "Auditorium B")
        self.assertEqual(slot["start"], "09:00")
        self.assertEqual(slot["end"], "10:00")

        # In multi-week window (June 1 - June 15), both General Lecture and Guest Lecture
        # overlap on Monday 09:00-10:00, correctly triggering weekly timetable conflict detection
        multi_plan = plan_ics_import(path, empty_timetable(), datetime.date(2026, 6, 1), datetime.date(2026, 6, 15))
        self.assertFalse(multi_plan.accepted)
        self.assertEqual(len(multi_plan.conflicts), 1)
        self.assertEqual(multi_plan.conflicts[0].day, "monday")

