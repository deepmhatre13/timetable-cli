    def test_override_moving_occurrence_into_import_window(self):
        """Original occurrence outside window, but override moves it inside window."""
        # Window: June 8 to June 15.
        # Master June 1 is BEFORE window (June 1, 8, 15).
        # Override for June 1 moves it to June 10 (inside window).
        ics_text = (
            "BEGIN:VCALENDAR\n"
            "VERSION:2.0\n"
            "BEGIN:VEVENT\n"
            "UID:move-into-window@example.com\n"
            "SUMMARY:Catchup Seminar\n"
            "DTSTART:20260601T100000\n"
            "DTEND:20260601T110000\n"
            "RRULE:FREQ=WEEKLY;COUNT=3\n"
            "END:VEVENT\n"
            "BEGIN:VEVENT\n"
            "UID:move-into-window@example.com\n"
            "RECURRENCE-ID:20260601T100000\n"
            "DTSTART:20260610T140000\n"
            "DTEND:20260610T150000\n"
            "END:VEVENT\n"
            "END:VCALENDAR\n"
        )
        path = self.write_ics(ics_text)
        from_date = datetime.date(2026, 6, 8)
        to_date = datetime.date(2026, 6, 15)

        plan = plan_ics_import(path, empty_timetable(), from_date, to_date)
        self.assertTrue(plan.accepted)
        # In window:
        # - June 8 (master)
        # - June 10 (override of June 1, moved into window)
        # - June 15 (master)
        self.assertEqual(plan.occurrences_generated, 3)
        days = {c[1] for c in plan.new_classes}
        self.assertEqual(days, {"monday", "wednesday"})
